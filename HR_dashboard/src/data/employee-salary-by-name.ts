/** 엑셀에 '이 대 현'처럼 띄어쓴 경우도 맞춤 */
function normalizePersonName(name: string) {
  return name.replace(/\s+/g, "").trim();
}

const SALARY_BY_NORMALIZED_NAME: Record<string, number> = Object.fromEntries(
  Object.entries(EMPLOYEE_SALARY_BY_NAME).map(([name, salary]) => [
    normalizePersonName(name),
    salary,
  ]),
);

export function applySalaryByName<T extends { name: string; salary: number }>(
  items: T[],
): { items: T[]; matched: number; unmatchedNames: string[] } {
  let matched = 0;
  const used = new Set<string>();
  const next = items.map((e) => {
    const key = normalizePersonName(e.name);
    const salary = SALARY_BY_NORMALIZED_NAME[key];
    if (salary == null) return e;
    used.add(key);
    matched += 1;
    return { ...e, salary };
  });
  const unmatchedNames = Object.keys(EMPLOYEE_SALARY_BY_NAME).filter(
    (n) => !used.has(normalizePersonName(n)),
  );
  return { items: next, matched, unmatchedNames };
}
